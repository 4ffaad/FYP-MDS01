class StorageError(ValueError):
    """Raised when an archive or storage operation is unsafe."""


_ENCRYPTED_MAGIC = b"MDS01GCM1"
_BOUND_ENCRYPTED_MAGIC = b"MDS01GCM2"
_CHUNKED_ENCRYPTED_MAGIC = b"MDS01VGC1"
_NONCE_BYTES = 12
_TAG_BYTES = 16
_CHUNKED_HEADER_BYTES = len(_CHUNKED_ENCRYPTED_MAGIC) + 4 + 8 + _NONCE_BYTES + _TAG_BYTES
_CHUNKED_BYTES = 1024 * 1024
_CHUNKED_RECORD_OVERHEAD = _NONCE_BYTES + _TAG_BYTES
_MAX_ANNOTATION_MEMBER_BYTES = 1024 * 1024
MAX_ARCHIVE_TOTAL_BYTES = int(os.getenv("MDS01_MAX_ARCHIVE_TOTAL_BYTES", str(2 * 1024**3)))
MAX_ZIP_COMPRESSION_RATIO = float(os.getenv("MDS01_MAX_ZIP_COMPRESSION_RATIO", "100"))
MAX_ARCHIVE_MEMBER_COUNT = int(os.getenv("MDS01_MAX_ARCHIVE_MEMBER_COUNT", "4096"))
_MAX_ARCHIVE_CENTRAL_DIRECTORY_BYTES = 64 * 1024**2
LOGGER = logging.getLogger(__name__)
if MAX_ARCHIVE_TOTAL_BYTES <= 0 or MAX_ZIP_COMPRESSION_RATIO <= 0 or MAX_ARCHIVE_MEMBER_COUNT <= 0:
    raise RuntimeError("Archive limits must be positive.")


class SessionStorage:
    """Manage private files for opaque analysis sessions.

    The class owns the directory layout but never exposes private paths in
    API responses. All original and derived artifacts are transient by default.
    """

    def __init__(self, root: Path = SESSION_STORAGE_DIR, storage_key: bytes | None = None) -> None:
        """Configure storage beneath a session-root directory.

        Parameters
        ----------
        root : pathlib.Path
            Parent directory for all session files.
        """

        self.root = root
        self.storage_key = storage_key

    def session_dir(self, session_id: str) -> Path:
        """Create and return the private root for one session.

        Parameters
        ----------
        session_id : str
            Opaque session identifier generated by the application.

        Returns
        -------
        pathlib.Path
            Session directory path for internal service use.
        """

        safe_id = self._safe_session_id(session_id)
        root = self.root
        if root.is_symlink() or (root.exists() and not root.is_dir()):
            raise StorageError("Private storage root is invalid.")
        root.mkdir(parents=True, exist_ok=True)
        path = root / safe_id
        if path.is_symlink() or (path.exists() and not path.is_dir()):
            raise StorageError("Private session storage is invalid.")
        path.mkdir(parents=True, exist_ok=True)
        os.chmod(root, 0o700)
        os.chmod(path, 0o700)
        return path

    @staticmethod
    def _safe_token(value: str, prefix: str) -> str:
        """Validate one opaque storage token without accepting a path."""

        if not value.startswith(prefix) or Path(value).name != value:
            raise StorageError("Storage identifier is invalid.")
        return value

    @staticmethod
    def _safe_session_id(value: str) -> str:
        """Validate an EEG or video session directory identifier."""

        if Path(value).name != value or not value.startswith(("SES-", "VID-")):
            raise StorageError("Storage identifier is invalid.")
        return value

    def _drafts_root(self, *, create: bool) -> Path:
        """Return the draft root without following a symlink."""

        path = self.root / "_drafts"
        if path.is_symlink():
            raise StorageError("Staged upload storage is invalid.")
        if path.exists():
            metadata = path.lstat()
            if metadata.st_mode & 0o170000 != 0o040000:
                raise StorageError("Staged upload storage is invalid.")
        elif create:
            path.mkdir(parents=True, exist_ok=True)
        return path

    def draft_dir(self, draft_id: str) -> Path:
        """Create and return the private directory for one staged upload."""

        safe_id = self._safe_token(draft_id, "UPL-")
        path = self._drafts_root(create=True) / safe_id
        path.mkdir(parents=True, exist_ok=True)
        os.chmod(self.root, 0o700)
        os.chmod(path.parent, 0o700)
        os.chmod(path, 0o700)
        return path

    def draft_path(self, draft_id: str) -> Path:
        """Return the encrypted archive path for one staged upload."""

        return self.draft_dir(draft_id) / "upload.zip.enc"

    def draft_size(self, draft_id: str) -> int:
        """Return a staged ciphertext size without following symlinks."""

        safe_id = self._safe_token(draft_id, "UPL-")
        path = self._drafts_root(create=False) / safe_id / "upload.zip.enc"
        try:
            metadata = path.lstat()
        except FileNotFoundError:
            return 0
        if not path.is_file() or metadata.st_mode & 0o170000 != 0o100000:
            raise StorageError("Staged upload storage is invalid.")
        return metadata.st_size

    def directory(self, session_id: str, name: str) -> Path:
        """Create and return one approved artifact directory.

        Parameters
        ----------
        session_id : str
            Opaque session identifier.
        name : str
            One of ``original``, ``work``, ``extracted``, ``deidentified``,
            ``processed``, ``retained``, or ``explanations``.

        Returns
        -------
        pathlib.Path
            Private directory for the requested artifact category.

        Raises
        ------
        StorageError
            Raised for unknown artifact categories.
        """

        if name not in {"original", "work", "extracted", "deidentified", "processed", "retained", "explanations"}:
            raise StorageError("Unknown session storage area.")
        path = self.session_dir(session_id) / name
        if path.is_symlink() or (path.exists() and not path.is_dir()):
            raise StorageError("Session storage area is invalid.")
        path.mkdir(parents=True, exist_ok=True)
        os.chmod(path, 0o700)
        return path

    async def save_upload(
        self,
        session_id: str,
        upload: UploadFile,
        *,
        max_bytes: int = MAX_UPLOAD_BYTES,
        filename: str = "upload.zip.enc",
    ) -> Path:
        """Stream an uploaded ZIP to private original-file storage.

        Parameters
        ----------
        session_id : str
            Opaque session identifier.
        upload : fastapi.UploadFile
            Multipart upload supplied by FastAPI.

        Returns
        -------
        pathlib.Path
            Internal path to the stored archive.

        Raises
        ------
        StorageError
            Raised for missing filenames or oversized uploads.
        """

        if not upload.filename:
            raise StorageError("Uploaded archive has no filename.")
        if Path(filename).name != filename or not filename:
            raise StorageError("Stored upload name is invalid.")
        destination = self.directory(session_id, "original") / filename
        return await self._encrypt_upload(upload, destination, max_bytes=max_bytes)

    async def save_chunked_upload(
        self,
        session_id: str,
        upload: UploadFile,
        *,
        filename: str,
        max_bytes: int,
        chunk_bytes: int = _CHUNKED_BYTES,
    ) -> Path:
        """Encrypt a media upload in independently authenticated random-access chunks."""

        if not upload.filename:
            raise StorageError("Uploaded media has no filename.")
        if Path(filename).name != filename or not filename:
            raise StorageError("Stored upload name is invalid.")
        destination = self.directory(session_id, "original") / filename
        return await self._encrypt_chunked_upload(
            upload, destination, max_bytes=max_bytes, chunk_bytes=chunk_bytes
        )

    async def _encrypt_chunked_upload(
        self,
        upload: UploadFile,
        destination: Path,
        *,
        max_bytes: int,
        chunk_bytes: int,
    ) -> Path:
        if not 64 * 1024 <= chunk_bytes <= 4 * 1024 * 1024:
            raise StorageError("Encrypted media chunk size is invalid.")
        aes = AESGCM(self._key())
        path_aad = self._associated_data(destination)
        total = 0
        chunk_count = 0
        flags = os.O_RDWR | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0)
        try:
            descriptor = os.open(destination, flags, 0o600)
            with os.fdopen(descriptor, "w+b") as output:
                output.write(b"\0" * _CHUNKED_HEADER_BYTES)
                while chunk := await upload.read(chunk_bytes):
                    total += len(chunk)
                    if total > max_bytes:
                        raise StorageError("Uploaded video exceeds the size limit.")
                    nonce = secrets.token_bytes(_NONCE_BYTES)
                    aad = self._chunk_aad(path_aad, chunk_count, len(chunk))
                    output.write(nonce)
                    output.write(aes.encrypt(nonce, chunk, aad))
                    chunk_count += 1
                if total == 0:
                    raise StorageError("Uploaded video is empty.")
                header_nonce = secrets.token_bytes(_NONCE_BYTES)
                header_aad = self._chunked_header_aad(
                    path_aad, chunk_bytes, total, chunk_count
                )
                header_tag = aes.encrypt(header_nonce, b"", header_aad)
                output.seek(0)
                output.write(_CHUNKED_ENCRYPTED_MAGIC)
                output.write(struct.pack(">IQ", chunk_bytes, total))
                output.write(header_nonce)
                output.write(header_tag)
        except Exception:
            destination.unlink(missing_ok=True)
            raise
        os.chmod(destination, 0o600)
        return destination

    def store_chunked_artifact(
        self,
        session_id: str,
        source_path: Path,
        name: str,
        *,
        chunk_bytes: int = _CHUNKED_BYTES,
    ) -> Path:
        """Encrypt a retained media artifact in authenticated random-access chunks."""

        if Path(name).name != name or not name:
            raise StorageError("Retained artifact name is invalid.")
        if source_path.is_symlink() or not source_path.is_file():
            raise StorageError("Plaintext media artifact is unavailable.")
        if not 64 * 1024 <= chunk_bytes <= 4 * 1024 * 1024:
            raise StorageError("Encrypted media chunk size is invalid.")
        destination = self.directory(session_id, "retained") / f"{name}.enc"
        aes = AESGCM(self._key())
        path_aad = self._associated_data(destination)
        total = 0
        chunk_count = 0
        flags = os.O_RDWR | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0)
        try:
            descriptor = os.open(destination, flags, 0o600)
            with source_path.open("rb") as source, os.fdopen(descriptor, "w+b") as output:
                output.write(b"\0" * _CHUNKED_HEADER_BYTES)
                while chunk := source.read(chunk_bytes):
                    total += len(chunk)
                    nonce = secrets.token_bytes(_NONCE_BYTES)
                    aad = self._chunk_aad(path_aad, chunk_count, len(chunk))
                    output.write(nonce)
                    output.write(aes.encrypt(nonce, chunk, aad))
                    chunk_count += 1
                if total == 0:
                    raise StorageError("Retained media artifact is empty.")
                header_nonce = secrets.token_bytes(_NONCE_BYTES)
                header_aad = self._chunked_header_aad(
                    path_aad, chunk_bytes, total, chunk_count
                )
                header_tag = aes.encrypt(header_nonce, b"", header_aad)
                output.seek(0)
                output.write(_CHUNKED_ENCRYPTED_MAGIC)
                output.write(struct.pack(">IQ", chunk_bytes, total))
                output.write(header_nonce)
                output.write(header_tag)
            os.chmod(destination, 0o600)
            source_path.unlink()
            return destination
        except Exception as exc:
            destination.unlink(missing_ok=True)
            if isinstance(exc, StorageError):
                raise
            raise StorageError("Retained media artifact could not be encrypted.") from exc

    @staticmethod
    def _chunk_aad(path_aad: bytes, chunk_index: int, chunk_length: int) -> bytes:
        return (
            b"MDS01 media chunk v1\0"
            + path_aad
            + struct.pack(">QI", chunk_index, chunk_length)
        )

    @staticmethod
    def _chunked_header_aad(
        path_aad: bytes, chunk_bytes: int, total_bytes: int, chunk_count: int
    ) -> bytes:
        return (
            b"MDS01 media header v1\0"
            + path_aad
            + struct.pack(">IQQ", chunk_bytes, total_bytes, chunk_count)
        )

    def _chunked_info(self, encrypted_path: Path) -> tuple[int, int, int, bytes]:
        try:
            with self._open_private_input(encrypted_path) as source:
                header = source.read(_CHUNKED_HEADER_BYTES)
                if len(header) != _CHUNKED_HEADER_BYTES or not header.startswith(_CHUNKED_ENCRYPTED_MAGIC):
                    raise StorageError("Stored media is not chunk-encrypted.")
                cursor = len(_CHUNKED_ENCRYPTED_MAGIC)
                chunk_bytes, total_bytes = struct.unpack_from(">IQ", header, cursor)
                cursor += 12
                header_nonce = header[cursor : cursor + _NONCE_BYTES]
                cursor += _NONCE_BYTES
                header_tag = header[cursor : cursor + _TAG_BYTES]
                if not 64 * 1024 <= chunk_bytes <= 4 * 1024 * 1024 or total_bytes <= 0:
                    raise StorageError("Encrypted media header is invalid.")
                chunk_count = math.ceil(total_bytes / chunk_bytes)
                expected_size = (
                    _CHUNKED_HEADER_BYTES
                    + total_bytes
                    + chunk_count * _CHUNKED_RECORD_OVERHEAD
                )
                if source.seek(0, os.SEEK_END) != expected_size:
                    raise StorageError("Encrypted media is incomplete.")
            path_aad = self._associated_data(encrypted_path)
            header_aad = self._chunked_header_aad(
                path_aad, chunk_bytes, total_bytes, chunk_count
            )
            AESGCM(self._key()).decrypt(header_nonce, header_tag, header_aad)
            return chunk_bytes, total_bytes, chunk_count, path_aad
        except StorageError:
            raise
        except Exception as exc:
            raise StorageError("Encrypted media header authentication failed.") from exc

    def is_chunked_envelope(self, encrypted_path: Path) -> bool:
        try:
            with self._open_private_input(encrypted_path) as source:
                return source.read(len(_CHUNKED_ENCRYPTED_MAGIC)) == _CHUNKED_ENCRYPTED_MAGIC
        except OSError as exc:
            raise StorageError("Encrypted media is unavailable.") from exc

    def chunked_plaintext_size(self, encrypted_path: Path) -> int:
        return self._chunked_info(encrypted_path)[1]

    def iter_decrypted_range(
        self, encrypted_path: Path, start: int, end: int
    ) -> Iterator[bytes]:
        """Yield one authenticated plaintext range without materializing the whole video."""

        chunk_bytes, total_bytes, chunk_count, path_aad = self._chunked_info(encrypted_path)
        if start < 0 or end < start or end >= total_bytes:
            raise StorageError("Encrypted media range is invalid.")
        first_chunk = start // chunk_bytes
        last_chunk = end // chunk_bytes
        aes = AESGCM(self._key())
        try:
            with self._open_private_input(encrypted_path) as source:
                for index in range(first_chunk, min(last_chunk + 1, chunk_count)):
                    plain_start = index * chunk_bytes
                    plain_length = min(chunk_bytes, total_bytes - plain_start)
                    record_offset = (
                        _CHUNKED_HEADER_BYTES + index * (chunk_bytes + _CHUNKED_RECORD_OVERHEAD)
                    )
                    source.seek(record_offset)
                    nonce = source.read(_NONCE_BYTES)
                    ciphertext = source.read(plain_length + _TAG_BYTES)
                    if len(nonce) != _NONCE_BYTES or len(ciphertext) != plain_length + _TAG_BYTES:
                        raise StorageError("Encrypted media chunk is incomplete.")
                    plaintext = aes.decrypt(
                        nonce,
                        ciphertext,
                        self._chunk_aad(path_aad, index, plain_length),
                    )
                    left = max(start, plain_start) - plain_start
                    right = min(end + 1, plain_start + plain_length) - plain_start
                    yield plaintext[left:right]
        except StorageError:
            raise
        except Exception as exc:
            raise StorageError("Encrypted media chunk authentication failed.") from exc

    def _materialize_chunked(self, encrypted_path: Path, destination: Path) -> Path:
        chunk_bytes, total_bytes, chunk_count, path_aad = self._chunked_info(encrypted_path)
        aes = AESGCM(self._key())
        try:
            with self._open_private_input(encrypted_path) as source, self._open_private_output(destination) as output:
                for index in range(chunk_count):
                    plain_length = min(chunk_bytes, total_bytes - index * chunk_bytes)
                    record_offset = (
                        _CHUNKED_HEADER_BYTES + index * (chunk_bytes + _CHUNKED_RECORD_OVERHEAD)
                    )
                    source.seek(record_offset)
                    nonce = source.read(_NONCE_BYTES)
                    ciphertext = source.read(plain_length + _TAG_BYTES)
                    if len(nonce) != _NONCE_BYTES or len(ciphertext) != plain_length + _TAG_BYTES:
                        raise StorageError("Encrypted media chunk is incomplete.")
                    output.write(
                        aes.decrypt(
                            nonce,
                            ciphertext,
                            self._chunk_aad(path_aad, index, plain_length),
                        )
                    )
            os.chmod(destination, 0o600)
            return destination
        except Exception:
            self._remove_plaintext_file(destination)
            raise

    async def save_draft_upload(self, draft_id: str, upload: UploadFile) -> Path:
        """Encrypt a ZIP into short-lived private draft storage."""

        return await self._encrypt_upload(upload, self.draft_path(draft_id), max_bytes=MAX_UPLOAD_BYTES)

    async def _encrypt_upload(self, upload: UploadFile, destination: Path, *, max_bytes: int) -> Path:
        """Stream one upload through AES-GCM into an owner-only file."""

        total = 0
        nonce = secrets.token_bytes(_NONCE_BYTES)
        encryptor = Cipher(algorithms.AES(self._key()), modes.GCM(nonce)).encryptor()
        encryptor.authenticate_additional_data(self._associated_data(destination))
        try:
            with self._open_private_output(destination) as output:
                output.write(_BOUND_ENCRYPTED_MAGIC)
                output.write(nonce)
                while chunk := await upload.read(1024 * 1024):
                    total += len(chunk)
                    if total > max_bytes:
                        raise StorageError("Uploaded archive exceeds the size limit.")
                    output.write(encryptor.update(chunk))
                output.write(encryptor.finalize())
                output.write(encryptor.tag)
        except Exception:
            destination.unlink(missing_ok=True)
            raise
        os.chmod(destination, 0o600)
        return destination

    def promote_draft(self, draft_id: str, session_id: str) -> Path:
        """Rebind an encrypted draft to its committed session storage path."""

        source = self.draft_path(draft_id)
        if not source.exists():
            raise StorageError("Upload draft was not found.")
        destination = self.directory(session_id, "original") / "upload.zip.enc"
        try:
            with self._open_private_input(source) as input_stream, self._open_private_output(destination) as output_stream:
                self._reencrypt_stream(input_stream, output_stream, source, destination)
        except FileExistsError as exc:
            raise StorageError("Session upload already exists.") from exc
        except Exception as exc:
            destination.unlink(missing_ok=True)
            if isinstance(exc, StorageError):
                raise
            raise StorageError("Staged archive cannot be promoted.") from exc
        return destination

    def delete_draft(self, draft_id: str) -> None:
        """Delete one staged archive and its private directory."""

        safe_id = self._safe_token(draft_id, "UPL-")
        drafts_root = self._drafts_root(create=False)
        if drafts_root.exists():
            self._remove_tree(drafts_root / safe_id)

    def cleanup_orphaned_drafts(self, active_draft_ids: set[str], older_than: datetime) -> None:
        """Remove old draft directories that have no database row."""

        drafts_root = self._drafts_root(create=False)
        if not drafts_root.exists():
            return
        for candidate in drafts_root.iterdir():
            if candidate.name in active_draft_ids or not candidate.name.startswith("UPL-"):
                continue
            metadata = candidate.lstat()
            if metadata.st_mode & 0o170000 != 0o040000:
                raise StorageError("Staged upload storage is invalid.")
            modified_at = datetime.fromtimestamp(metadata.st_mtime, timezone.utc)
            if modified_at <= older_than:
                self._remove_tree(candidate)

    def _key(self) -> bytes:
        """Return the injected test key or the required runtime storage key."""

        try:
            return self.storage_key or read_base64_key(STORAGE_KEY_ENV)
        except CryptoError as exc:
            raise StorageError(str(exc)) from exc

    def materialize_archive(self, session_id: str, encrypted_path: Path, *, deadline: float | None = None) -> Path:
        """Decrypt one private ZIP into a short-lived, owner-only work path."""

        safe_path = self._validate_materialization_source(session_id, encrypted_path)
        destination = self.directory(session_id, "work") / "upload.zip"
        return self._materialize_encrypted(safe_path, destination, deadline=deadline)

    def materialize_retained_artifact(
        self, session_id: str, encrypted_path: Path, name: str, *, deadline: float | None = None
    ) -> Path:
        """Decrypt one retained artifact into temporary private work storage."""

        if Path(name).name != name or not name:
            raise StorageError("Retained artifact name is invalid.")
        safe_path = self._validate_materialization_source(session_id, encrypted_path)
        destination = self.directory(session_id, "work") / name
        return self._materialize_encrypted(safe_path, destination, deadline=deadline)

    def _validate_materialization_source(self, session_id: str, encrypted_path: Path) -> Path:
        """Require an existing regular ciphertext below one session root."""

        safe_id = self._safe_session_id(session_id)
        root = Path(os.path.abspath(self.root))
        if root.is_symlink() or not root.is_dir():
            raise StorageError("Private storage root is invalid.")
        session_root = root / safe_id
        candidate = Path(os.path.abspath(encrypted_path))
        try:
            relative = candidate.relative_to(session_root)
        except ValueError as exc:
            raise StorageError("Stored artifact path is outside its session.") from exc
        if session_root.is_symlink() or not session_root.is_dir():
            raise StorageError("Private session storage is invalid.")
        current = session_root
        for part in relative.parts[:-1]:
            current /= part
            if current.is_symlink() or not current.is_dir():
                raise StorageError("Stored artifact path is invalid.")
        try:
            metadata = candidate.lstat()
        except FileNotFoundError as exc:
            raise StorageError("Stored artifact was not found.") from exc
        if stat.S_ISLNK(metadata.st_mode) or not stat.S_ISREG(metadata.st_mode):
            raise StorageError("Stored artifact path is invalid.")
        return candidate

    def _materialize_encrypted(
        self, encrypted_path: Path, destination: Path, *, deadline: float | None = None
    ) -> Path:
        """Decrypt one AES-GCM file and remove the plaintext on failure."""

        try:
            if destination.is_symlink() or (destination.exists() and not destination.is_file()):
                raise StorageError("Plaintext destination is invalid.")
            if self.is_chunked_envelope(encrypted_path):
                return self._materialize_chunked(encrypted_path, destination)
            size = encrypted_path.stat().st_size
            minimum_size = len(_ENCRYPTED_MAGIC) + _NONCE_BYTES + _TAG_BYTES
            if size < minimum_size:
                raise StorageError("Stored archive is incomplete.")
            with encrypted_path.open("rb") as source:
                magic = source.read(len(_ENCRYPTED_MAGIC))
                if magic not in {_ENCRYPTED_MAGIC, _BOUND_ENCRYPTED_MAGIC}:
                    raise StorageError("Stored archive is not encrypted.")
                nonce = source.read(_NONCE_BYTES)
                source.seek(size - _TAG_BYTES)
                tag = source.read(_TAG_BYTES)
                source.seek(len(_ENCRYPTED_MAGIC) + _NONCE_BYTES)
                remaining = size - len(_ENCRYPTED_MAGIC) - _NONCE_BYTES - _TAG_BYTES
                decryptor = Cipher(algorithms.AES(self._key()), modes.GCM(nonce, tag)).decryptor()
                if magic == _BOUND_ENCRYPTED_MAGIC:
                    decryptor.authenticate_additional_data(self._associated_data(encrypted_path))
                with self._open_private_output(destination) as output:
                    while remaining:
                        if deadline is not None and time.monotonic() > deadline:
                            raise StorageError("Stored artifact materialization timed out.")
                        chunk = source.read(min(1024 * 1024, remaining))
                        if not chunk:
                            raise StorageError("Stored archive is incomplete.")
                        remaining -= len(chunk)
                        output.write(decryptor.update(chunk))
                    output.write(decryptor.finalize())
            os.chmod(destination, 0o600)
            if magic == _ENCRYPTED_MAGIC:
                self._upgrade_legacy_envelope(encrypted_path, destination)
            return destination
        except StorageError:
            self._remove_plaintext_file(destination)
            raise
        except Exception as exc:
            self._remove_plaintext_file(destination)
            raise StorageError("Stored archive cannot be decrypted.") from exc

    def _associated_data(self, path: Path) -> bytes:
        """Bind new ciphertext to its canonical private-storage-relative path."""

        root = Path(os.path.abspath(self.root))
        candidate = Path(os.path.abspath(path))
        try:
            relative = candidate.relative_to(root)
        except ValueError as exc:
            raise StorageError("Stored artifact path is outside private storage.") from exc
        if not relative.parts or ".." in relative.parts:
            raise StorageError("Stored artifact path is invalid.")
        return b"MDS01 private storage v2\0" + relative.as_posix().encode("utf-8")

    def _reencrypt_stream(
        self,
        source,
        destination,
        source_path: Path,
        destination_path: Path,
    ) -> None:
        """Authenticate a staged envelope and encrypt it for its final path."""

        size = os.fstat(source.fileno()).st_size
        minimum_size = len(_ENCRYPTED_MAGIC) + _NONCE_BYTES + _TAG_BYTES
        if size < minimum_size:
            raise StorageError("Staged archive is incomplete.")
        magic = source.read(len(_ENCRYPTED_MAGIC))
        if magic not in {_ENCRYPTED_MAGIC, _BOUND_ENCRYPTED_MAGIC}:
            raise StorageError("Staged archive is not encrypted.")
        source_nonce = source.read(_NONCE_BYTES)
        source.seek(size - _TAG_BYTES)
        source_tag = source.read(_TAG_BYTES)
        source.seek(len(_ENCRYPTED_MAGIC) + _NONCE_BYTES)
        remaining = size - len(_ENCRYPTED_MAGIC) - _NONCE_BYTES - _TAG_BYTES

        decryptor = Cipher(
            algorithms.AES(self._key()), modes.GCM(source_nonce, source_tag)
        ).decryptor()
        if magic == _BOUND_ENCRYPTED_MAGIC:
            decryptor.authenticate_additional_data(self._associated_data(source_path))

        destination_nonce = secrets.token_bytes(_NONCE_BYTES)
        encryptor = Cipher(algorithms.AES(self._key()), modes.GCM(destination_nonce)).encryptor()
        encryptor.authenticate_additional_data(self._associated_data(destination_path))
        destination.write(_BOUND_ENCRYPTED_MAGIC)
        destination.write(destination_nonce)
        while remaining:
            chunk = source.read(min(1024 * 1024, remaining))
            if not chunk:
                raise StorageError("Staged archive is incomplete.")
            remaining -= len(chunk)
            destination.write(encryptor.update(decryptor.update(chunk)))
        destination.write(encryptor.update(decryptor.finalize()))
        destination.write(encryptor.finalize())
        destination.write(encryptor.tag)

    def _encrypt_stream(self, source, destination, destination_path: Path) -> None:
        """Encrypt a plaintext stream in the current path-bound envelope."""

        nonce = secrets.token_bytes(_NONCE_BYTES)
        encryptor = Cipher(algorithms.AES(self._key()), modes.GCM(nonce)).encryptor()
        encryptor.authenticate_additional_data(self._associated_data(destination_path))
        destination.write(_BOUND_ENCRYPTED_MAGIC)
        destination.write(nonce)
        while chunk := source.read(1024 * 1024):
            destination.write(encryptor.update(chunk))
        destination.write(encryptor.finalize())
        destination.write(encryptor.tag)

    def _upgrade_legacy_envelope(self, encrypted_path: Path, plaintext_path: Path) -> None:
        """Atomically rewrap a successfully decrypted legacy file when possible."""

        temporary = encrypted_path.with_name(
            f".{encrypted_path.name}.{secrets.token_hex(12)}.tmp"
        )
        try:
            with self._open_private_input(plaintext_path) as source, self._open_private_output(
                temporary
            ) as output:
                self._encrypt_stream(source, output, encrypted_path)
                output.flush()
                os.fsync(output.fileno())
            os.replace(temporary, encrypted_path)
            os.chmod(encrypted_path, 0o600)
            directory_fd = os.open(
                encrypted_path.parent,
                os.O_RDONLY | getattr(os, "O_DIRECTORY", 0),
            )
            try:
                os.fsync(directory_fd)
            finally:
                os.close(directory_fd)
        except Exception:
            temporary.unlink(missing_ok=True)
            LOGGER.warning("Legacy private-storage envelope upgrade was deferred.")

    @staticmethod
    def _remove_plaintext_file(path: Path) -> None:
        try:
            metadata = path.lstat()
        except FileNotFoundError:
            return
        if stat.S_ISREG(metadata.st_mode) or stat.S_ISLNK(metadata.st_mode):
            path.unlink(missing_ok=True)

    @staticmethod
    def _open_private_input(path: Path):
        """Open a regular private file without following a symlink."""

        flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0)
        return os.fdopen(os.open(path, flags), "rb")

    @staticmethod
    def _open_private_output(path: Path):
        """Create a new owner-only file without following a symlink."""

        flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0)
        return os.fdopen(os.open(path, flags, 0o600), "wb")

    def store_encrypted_artifact(self, session_id: str, source_path: Path, name: str) -> Path:
        """Encrypt one retained derived artifact and return its private path.

        Parameters
        ----------
        session_id : str
            Opaque session identifier.
        source_path : pathlib.Path
            Temporary plaintext artifact to encrypt and remove on success.
        name : str
            Safe artifact basename, without a user-controlled path.

        Returns
        -------
        pathlib.Path
            Private encrypted artifact path.

        Raises
        ------
        StorageError
            Raised when the source is invalid or encryption fails.
        """

        if Path(name).name != name or not name:
            raise StorageError("Retained artifact name is invalid.")
        destination = self.directory(session_id, "retained") / f"{name}.enc"
        try:
            with self._open_private_input(Path(source_path)) as source, self._open_private_output(destination) as output:
                self._encrypt_stream(source, output, destination)
            os.chmod(destination, 0o600)
            return destination
        except Exception as exc:
            destination.unlink(missing_ok=True)
            raise StorageError("Retained artifact could not be encrypted.") from exc
        finally:
            Path(source_path).unlink(missing_ok=True)

    @staticmethod
    def _safe_member_path(member_name: str) -> PurePosixPath:
        """Validate one ZIP member path against traversal attacks.

        Parameters
        ----------
        member_name : str
            Path supplied by the ZIP archive.

        Returns
        -------
        pathlib.PurePosixPath
            Normalized safe archive-relative path.

        Raises
        ------
        StorageError
            Raised for absolute paths, parent traversal, or invalid names.
        """

        member_name = member_name.replace("\\", "/")
        candidate = PurePosixPath(member_name)
        if candidate.is_absolute() or ".." in candidate.parts:
            raise StorageError("Archive contains an unsafe path.")
        if not candidate.name:
            raise StorageError("Archive contains an invalid file path.")
        return candidate

    @staticmethod
    def _is_hidden_member(path: PurePosixPath) -> bool:
        """Return whether a ZIP member is hidden operating-system metadata."""

        return any(part == "__MACOSX" or part.startswith(".") for part in path.parts)

    @staticmethod
    def _archive_member_key(path: PurePosixPath) -> str:
        """Return a canonical key for case- and Unicode-equivalent ZIP paths."""

        return unicodedata.normalize("NFC", path.as_posix()).casefold()

    @classmethod
    def _validated_archive_members(cls, archive: zipfile.ZipFile) -> list[zipfile.ZipInfo]:
        """Validate ZIP metadata before any member is read or extracted."""

        members = archive.infolist()
        if len(members) > MAX_ARCHIVE_MEMBER_COUNT:
            raise StorageError("ZIP archive contains too many members.")

        total_uncompressed = 0
        total_compressed = 0
        for member in members:
            mode = (member.external_attr >> 16) & 0o170000
            if mode in {stat.S_IFLNK, stat.S_IFCHR, stat.S_IFBLK, stat.S_IFIFO, stat.S_IFSOCK}:
                raise StorageError("Archive contains a special file.")
            if member.file_size < 0 or member.compress_size < 0:
                raise StorageError("Archive contains invalid size metadata.")
            if member.is_dir():
                continue
            if member.file_size > MAX_ARCHIVE_MEMBER_BYTES:
                raise StorageError("Archive member exceeds the size limit.")
            total_uncompressed += member.file_size
            total_compressed += member.compress_size
            if total_uncompressed > MAX_ARCHIVE_TOTAL_BYTES:
                raise StorageError("ZIP archive exceeds the cumulative total size limit.")
            if member.file_size / max(member.compress_size, 1) > MAX_ZIP_COMPRESSION_RATIO:
                raise StorageError("Archive member exceeds the safe compression ratio.")
        if total_compressed > MAX_UPLOAD_BYTES:
            raise StorageError("ZIP archive exceeds the compressed size limit.")
        return members

    @staticmethod
    def _preflight_zip_directory(stream: BinaryIO) -> None:
        """Bound entry count and central-directory bytes before ZipFile loads them."""

        try:
            # zipfile exposes no public preflight API; reuse its own bounded
            # EOCD/ZIP64 parser so trailer handling matches ZipFile itself.
            end_record_reader = getattr(zipfile, "_EndRecData")
            member_count_index = getattr(zipfile, "_ECD_ENTRIES_TOTAL")
            directory_size_index = getattr(zipfile, "_ECD_SIZE")
            end_record = end_record_reader(stream)
            if end_record is None:
                raise StorageError("Archive central directory is invalid.")
            member_count = int(end_record[member_count_index])
            directory_size = int(end_record[directory_size_index])
        except (AttributeError, IndexError, OSError, TypeError, ValueError, zipfile.BadZipFile) as exc:
            raise StorageError("Archive central directory is invalid.") from exc
        if member_count < 0 or member_count > MAX_ARCHIVE_MEMBER_COUNT:
            raise StorageError("ZIP archive contains too many members.")
        if directory_size < 0 or directory_size > _MAX_ARCHIVE_CENTRAL_DIRECTORY_BYTES:
            raise StorageError("ZIP archive central directory exceeds the safe size limit.")

    @contextmanager
    def _open_bounded_zip(self, archive_path: Path) -> Iterator[zipfile.ZipFile]:
        """Preflight one archive before opening its directory entries."""

        with archive_path.open("rb") as stream:
            self._preflight_zip_directory(stream)
            stream.seek(0)
            with zipfile.ZipFile(stream) as archive:
                yield archive

    def read_reference_annotations(self, archive_path: Path) -> dict[str, tuple[str, list[tuple[float, float]]]]:
        """Read optional CHB-MIT reference intervals without retaining source names."""

        annotations: dict[str, tuple[str, list[tuple[float, float]]]] = {}
        summaries: dict[str, list[tuple[float, float]]] = {}
        sidecars: dict[str, list[tuple[float, float]]] = {}
        with self._open_bounded_zip(archive_path) as archive:
            for member in self._validated_archive_members(archive):
                if member.is_dir():
                    continue
                relative = self._safe_member_path(member.filename)
                if self._is_hidden_member(relative) or member.file_size > _MAX_ANNOTATION_MEMBER_BYTES:
                    continue
                lower_name = relative.name.lower()
                try:
                    if lower_name.endswith("-summary.txt"):
                        text = archive.read(member).decode("utf-8-sig")
                        summaries.update(summary_annotations(text))
                    elif lower_name.endswith(".edf.seizures"):
                        edf_name = lower_name.removesuffix(".seizures")
                        sidecars[edf_name] = sidecar_annotations(archive.read(member))
                except (UnicodeDecodeError, ValueError):
                    continue

        for filename, intervals in sidecars.items():
            annotations[filename] = ("chb-mit-sidecar", intervals)
        for filename, intervals in summaries.items():
            annotations[filename] = ("chb-mit-summary", intervals)
        return annotations

    def read_embedded_eeg_events(self, extracted_paths: list[Path]) -> dict[str, list[dict[str, object]]]:
        """Read sanitized event timing from extracted legacy Nicolet files.

        Raw annotation text, patient fields, and source paths are deliberately
        excluded. The returned values are suitable for private alignment and
        review workflows, not automatic clinical labeling.
        """

        events_by_filename: dict[str, list[dict[str, object]]] = {}
        for path in extracted_paths:
            if path.suffix.lower() != ".e":
                continue
            try:
                events = read_legacy_eeg_events(path)
            except (OSError, ValueError):
                # Annotation extraction is best-effort at the session level.
                # The recording's normal validation pass will fail only this
                # source if its embedded event section is structurally invalid.
                continue
            events_by_filename[path.name.lower()] = [
                {
                    "onset_seconds": event.onset_seconds,
                    "duration_seconds": event.duration_seconds,
                    "kind": event.kind,
                    "text_present": event.text_present,
                }
                for event in events
            ]
        return events_by_filename

    def extract_eeg_recordings(self, session_id: str, archive_path: Path) -> list[Path]:
        """Extract validated EDF or Nicolet members into session storage.

        Parameters
        ----------
        session_id : str
            Opaque session identifier.
        archive_path : pathlib.Path
            Private ZIP archive path.

        Returns
        -------
        list[pathlib.Path]
            Extracted EEG primary paths in natural filename order.

        Raises
        ------
        StorageError
            Raised for missing EEG files, incomplete Nicolet pairs, unsafe
            paths, duplicate basenames, oversized members, or too many
            recordings.
        """

        extracted_dir = self.directory(session_id, "extracted")
        with self._open_bounded_zip(archive_path) as archive:
            all_members: list[tuple[zipfile.ZipInfo, PurePosixPath]] = []
            normalized_names: set[str] = set()
            for member in self._validated_archive_members(archive):
                if member.is_dir():
                    continue
                relative = self._safe_member_path(member.filename)
                if self._is_hidden_member(relative):
                    continue
                normalized_name = self._archive_member_key(relative)
                if normalized_name in normalized_names:
                    raise StorageError("ZIP archive contains a duplicate archive member path.")
                normalized_names.add(normalized_name)
                all_members.append((member, relative))
            member_by_name = {
                self._archive_member_key(relative): (member, relative)
                for member, relative in all_members
            }
            members: list[tuple[zipfile.ZipInfo, PurePosixPath, tuple[zipfile.ZipInfo, PurePosixPath] | None]] = []
            for member, relative in all_members:
                suffix = relative.suffix.lower()
                if suffix == ".edf":
                    members.append((member, relative, None))
                elif suffix == ".data":
                    header_key = self._archive_member_key(relative.with_suffix(".head"))
                    header = member_by_name.get(header_key)
                    if header is None or header[0].is_dir():
                        raise StorageError("Nicolet .data recording is missing its matching .head file.")
                    members.append((member, relative, header))
                elif suffix == ".e":
                    members.append((member, relative, None))
            if not members:
                raise StorageError("ZIP archive does not contain EDF, legacy Nicolet .e, or supported Nicolet .data EEG files.")
            if len(members) > MAX_EDF_FILES_PER_ARCHIVE:
                raise StorageError("ZIP archive contains too many EEG files.")
            outputs: list[Path] = []
            natural_key = lambda item: [
                int(part) if part.isdigit() else part.lower()
                for part in re.split(r"(\d+)", item[1].name)
            ]
            ordered_members = sorted(members, key=natural_key)
            used_names: set[str] = set()
            for _, relative, header in ordered_members:
                # Store only the basename to prevent user-controlled directory
                # layouts from escaping the session boundary.
                suffix = relative.suffix.lower()
                destination_name = f"{relative.stem}{suffix}"
                destination_key = self._archive_member_key(PurePosixPath(destination_name))
                if destination_key in used_names:
                    raise StorageError("Archive contains duplicate EEG filenames.")
                used_names.add(destination_key)
                if header is not None:
                    header_name = f"{PurePosixPath(destination_name).stem}.head"
                    header_key = self._archive_member_key(PurePosixPath(header_name))
                    if header_key in used_names:
                        raise StorageError("Archive contains duplicate Nicolet header filenames.")
                    used_names.add(header_key)

            for member, relative, header in ordered_members:
                suffix = relative.suffix.lower()
                destination_name = f"{relative.stem}{suffix}"
                destination = extracted_dir / destination_name
                with archive.open(member) as source, destination.open("wb") as output:
                    shutil.copyfileobj(source, output)
                os.chmod(destination, 0o600)
                if header is not None:
                    header_destination = extracted_dir / f"{destination.stem}.head"
                    with archive.open(header[0]) as source, header_destination.open("wb") as output:
                        shutil.copyfileobj(source, output)
                    os.chmod(header_destination, 0o600)
                outputs.append(destination)
            return outputs

    def extract_edfs(self, session_id: str, archive_path: Path) -> list[Path]:
        """Backward-compatible extraction entry point for EDF and Nicolet."""

        return self.extract_eeg_recordings(session_id, archive_path)

    @contextmanager
    def read_lease(self, session_id: str):
        """Prevent cleanup from removing plaintext while an owner reads it."""
        root = self.session_dir(session_id)
        descriptor = os.open(root / ".read.lock", os.O_CREAT | os.O_RDWR | getattr(os, "O_NOFOLLOW", 0), 0o600)
        try:
            if not stat.S_ISREG(os.fstat(descriptor).st_mode):
                raise StorageError("Private read lease is invalid.")
            fcntl.flock(descriptor, fcntl.LOCK_SH)
            yield
        finally:
            os.close(descriptor)

    def cleanup_session(self, session_id: str, **kwargs) -> None:
        root = self.root / self._safe_session_id(session_id)
        if not root.exists():
            return
        self.session_dir(session_id)
        descriptor = os.open(root / ".read.lock", os.O_CREAT | os.O_RDWR | getattr(os, "O_NOFOLLOW", 0), 0o600)
        try:
            try:
                fcntl.flock(descriptor, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                return
            self._cleanup_session(session_id, **kwargs)
        finally:
            os.close(descriptor)

    def _cleanup_session(
        self,
        session_id: str,
        *,
        keep_retained: bool = False,
        preserve_work_files: set[str] | None = None,
        keep_original: bool = False,
    ) -> None:
        """Delete transient session files after processing.

        Parameters
        ----------
        session_id : str
            Opaque session identifier.
        keep_retained : bool
            Preserve encrypted model-positive artifacts when true.
        """

        session_dir = self.root / self._safe_session_id(session_id)
        if not keep_retained:
            self._remove_tree(session_dir)
            return
        preserved = preserve_work_files or set()
        for name in ("original", "work", "extracted", "deidentified", "processed", "explanations"):
            if name == "original" and keep_original:
                continue
            area = session_dir / name
            if name != "work" or not preserved:
                self._remove_tree(area)
                continue
            if area.is_symlink() or (area.exists() and not area.is_dir()):
                raise StorageError("Private work storage is invalid.")
            if area.exists():
                for child in area.iterdir():
                    if child.name in preserved:
                        if child.is_symlink() or not child.is_file():
                            raise StorageError("Preserved work file is invalid.")
                        continue
                    metadata = child.lstat()
                    if stat.S_ISDIR(metadata.st_mode):
                        self._remove_tree(child)
                    elif stat.S_ISREG(metadata.st_mode):
                        child.unlink()
                    else:
                        raise StorageError("Private work entry is invalid.")

    @staticmethod
    def _remove_tree(path: Path) -> None:
        """Remove a private directory and fail closed if deletion fails."""

        if not path.exists():
            if path.is_symlink():
                raise StorageError("Private storage cleanup encountered a symlink.")
            return
        try:
            shutil.rmtree(path)
        except OSError as exc:
            raise StorageError("Private storage cleanup failed.") from exc
        if path.exists():
            raise StorageError("Private storage cleanup could not be verified.")

    def delete_retained_artifact(self, path: Path) -> None:
        """Delete one encrypted retained artifact after a recording failure.

        Parameters
        ----------
        path : pathlib.Path
            Internal retained-artifact path created by this storage service.

        Raises
        ------
        StorageError
            Raised when the path is outside this storage service's retained
            directories.
        """

        retained_root = self.root.resolve()
        candidate = path.resolve()
        if retained_root not in candidate.parents or candidate.parent.name != "retained":
            raise StorageError("Retained artifact path is invalid.")
        candidate.unlink(missing_ok=True)

    def delete_session(self, session_id: str) -> None:
        """Delete all private files belonging to one user-requested session.

        Parameters
        ----------
        session_id : str
            Opaque session identifier whose protected storage should be removed.
        """

        root = self.root / self._safe_session_id(session_id)
        if not root.exists():
            return
        self.session_dir(session_id)
        descriptor = os.open(
            root / ".read.lock",
            os.O_CREAT | os.O_RDWR | getattr(os, "O_NOFOLLOW", 0),
            0o600,
        )
        try:
            if not stat.S_ISREG(os.fstat(descriptor).st_mode):
                raise StorageError("Private deletion lock is invalid.")
            fcntl.flock(descriptor, fcntl.LOCK_EX)
            self._remove_tree(root)
        finally:
            os.close(descriptor)

    def cleanup_expired_drafts(self, draft_ids: list[str]) -> None:
        """Remove expired staged upload directories."""

        for draft_id in draft_ids:
            self.delete_draft(draft_id)
